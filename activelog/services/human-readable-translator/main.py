    def _detect_highlevel_patterns(self, code_snippet: str, language: str) -> List[Dict[str, Any]]:
        """Detect patterns in high-level language code"""
        patterns = []
        lines = code_snippet.strip().split('\n')
        
        # Language-specific pattern detection
        for line in lines:
            line_stripped = line.strip().lower()
            
            if language in ["python", "javascript", "typescript"]:
                if "def " in line_stripped or "function" in line_stripped:
                    patterns.append({"type": "function_definition", "line": line.strip()})
                elif "if " in line_stripped:
                    patterns.append({"type": "conditional", "line": line.strip()})
                elif "for " in line_stripped or "while " in line_stripped:
                    patterns.append({"type": "loop", "line": line.strip()})
                elif "=" in line_stripped and not ("==" in line_stripped or "!=" in line_stripped):
                    patterns.append({"type": "assignment", "line": line.strip()})
            
            elif language in ["c++", "rust", "c"]:
                if "#include" in line_stripped or "use " in line_stripped:
                    patterns.append({"type": "import", "line": line.strip()})
                elif "struct " in line_stripped or "class " in line_stripped:
                    patterns.append({"type": "type_definition", "line": line.strip()})
                elif "*" in line_stripped and ("malloc" in line_stripped or "new" in line_stripped):
                    patterns.append({"type": "memory_allocation", "line": line.strip()})
        
        return patterns

