    def _find_best_language_match(self, patterns: List[Dict[str, Any]]) -> str:
        """Find the best language match for given assembly patterns"""
        # Language capability scores
        language_scores = {
            "python": 0,
            "typescript": 0, 
            "rust": 0,
            "c++": 0,
            "go": 0,
            "java": 0
        }
        
        # Score languages based on pattern compatibility
        for pattern in patterns:
            pattern_type = pattern["type"]
            if pattern_type in ["mov", "cmp", "jmp"]:
                language_scores["python"] += 1
                language_scores["typescript"] += 1
            if pattern_type in ["push", "pop", "call"]:
                language_scores["c++"] += 2
                language_scores["rust"] += 2
            if pattern_type == "loop":
                for lang in language_scores:
                    language_scores[lang] += 1
        
        # Return language with highest score
        return max(language_scores.items(), key=lambda x: x[1])[0]

