    async def translate_assembly_to_human(self, assembly_code: str, target_language: str = None, context: Dict[str, Any] = None):
        """Translate assembly code to human-readable code in target language"""
        if target_language and target_language not in self.supported_languages:
            raise ValueError(f"Unsupported language: {target_language}")
        
        # Analyze assembly patterns
        detected_patterns = self._detect_assembly_patterns(assembly_code)
        
        # If no target language specified, find best match
        if not target_language:
            target_language = self._find_best_language_match(detected_patterns)
        
        logger.info(f"🔄 Translating assembly to {target_language}...")
        
        # Generate human-readable code
        human_code = await self._generate_human_readable_code(
            detected_patterns, target_language, context
        )
        
        # Calculate readability and performance scores
        readability_score = self._calculate_readability_score(human_code, target_language)
        performance_retention = self._estimate_performance_retention(detected_patterns)
        
        # Store translation
        cursor = self.conn.cursor()
        cursor.execute('''
            INSERT INTO translations
            (source_assembly, target_language, human_readable_code, optimization_notes, 
             readability_score, performance_retention, timestamp)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        ''', (
            assembly_code,
            target_language,
            human_code,
            f"Detected patterns: {', '.join([p['type'] for p in detected_patterns])}",
            readability_score,
            performance_retention,
            datetime.now()
        ))
        
        self.conn.commit()
        
        translation_result = {
            "source_assembly": assembly_code,
            "target_language": target_language,
            "human_readable_code": human_code,
            "detected_patterns": detected_patterns,
            "readability_score": readability_score,
            "performance_retention": performance_retention,
            "explanation": "Assembly-optimized code translated to human-readable format with detailed comments"
        }
        
        logger.info(f"✅ Translation complete - Readability: {readability_score:.1%}, Performance retention: {performance_retention:.1%}")
        return translation_result

    async def translate_with_preferences(self, assembly_code: str, language_preferences: List[str], context: Dict[str, Any] = None):
        """Translate assembly code using developer's language preferences (e.g., ['python', 'c', 'r'])"""
        logger.info(f"🎯 Translating with preferences: {', '.join(language_preferences)}")
        
        # Analyze assembly patterns
        detected_patterns = self._detect_assembly_patterns(assembly_code)
        
        # Try each language in preference order
        attempted_languages = []
