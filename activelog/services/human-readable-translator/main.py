    def _auto_detect_language(self, code_snippet: str) -> str:
        """Auto-detect programming language from code snippet"""
        code_lower = code_snippet.lower().strip()
        
        # Assembly indicators
        if any(keyword in code_lower for keyword in ["mov ", "cmp ", "jmp ", "push ", "pop ", "call "]):
            return "assembly"
        
        # Python indicators
        elif "def " in code_lower or "import " in code_lower or code_snippet.count(":") > code_snippet.count(";"):
            return "python"
        
        # JavaScript/TypeScript indicators
        elif "function " in code_lower or "const " in code_lower or "let " in code_lower or "var " in code_lower:
            return "javascript"
        
        # C++ indicators
        elif "#include" in code_lower or "std::" in code_lower or "cout" in code_lower:
            return "c++"
        
        # Rust indicators
        elif "fn " in code_lower or "let mut" in code_lower or "use " in code_lower and "::" in code_lower:
            return "rust"
        
        # Java indicators
        elif "public class" in code_lower or "System.out" in code_lower or "public static void main" in code_lower:
            return "java"
        
        # Default to assembly if uncertain
        else:
            return "assembly"

    def _detect_assembly_patterns(self, assembly_code: str) -> List[Dict[str, Any]]:
        """Detect patterns in assembly code"""
        patterns = []
        lines = assembly_code.strip().split('\n')
        
        for line in lines:
            line = line.strip().lower()
            for pattern_type, pattern_info in self.translation_patterns.items():
                if pattern_type in line or any(keyword in line for keyword in [pattern_type]):
                    patterns.append({
                        "type": pattern_type,
                        "line": line,
                        "translation_info": pattern_info
                    })
        
        return patterns

    async def _generate_human_readable_code(self, patterns: List[Dict[str, Any]], target_language: str, context: Dict[str, Any] = None) -> str:
        """Generate human-readable code from assembly patterns"""
        template = self.code_templates.get(target_language, self.code_templates["python"])
        
        # Build function context
        function_name = (context or {}).get("function_name", "assembly_optimized_function")
        parameters = (context or {}).get("parameters", "args")
        description = (context or {}).get("description", "Assembly-optimized function for maximum bot efficiency")
        
        # Start with file header and function signature
        code_lines = [
            template["file_header"],
            template["function_start"].format(
                function_name=function_name,
                parameters=parameters,
                description=description,
                assembly_notes="This function contains assembly-level optimizations"
            )
        ]
        
        # Add human-readable implementations of detected patterns
        for i, pattern in enumerate(patterns):
            pattern_type = pattern["type"]
            pattern_info = pattern["translation_info"]
            
            # Add assembly comment
            assembly_comment = template["assembly_comment"].format(
                operation=pattern_type.replace("_", " ").title(),
                assembly_code=pattern_info["assembly"]
            )
            code_lines.append(assembly_comment)
            
            # Add human-readable implementation
            if target_language == "python":
                implementation = pattern_info["python"]
            elif target_language in ["typescript", "javascript"]:
                implementation = pattern_info["typescript"]
            else:
                implementation = pattern_info["python"]  # fallback
            
            # Indent properly
            indented_implementation = "    " + implementation.replace("\n", "\n    ")
            code_lines.append(indented_implementation + "\n")
        
        # Add return statement
        if target_language == "python":
            code_lines.append("    return result  # Assembly-optimized return\n")
        elif target_language in ["typescript", "javascript"]:
            code_lines.append("    return result; // Assembly-optimized return\n")
            code_lines.append("}\n")
        
        return "".join(code_lines)

    def _calculate_readability_score(self, code: str, language: str) -> float:
        """Calculate readability score of generated code"""
        # Simple readability metrics
        lines = code.split('\n')
        comment_lines = len([l for l in lines if '//' in l or '#' in l])
        total_lines = len([l for l in lines if l.strip()])
        
        comment_ratio = comment_lines / max(total_lines, 1)
        
        # Base readability score
        base_score = 0.7
        
        # Bonus for good commenting
        comment_bonus = min(comment_ratio * 0.3, 0.2)
        
        # Language-specific adjustments
        language_bonus = {
            "python": 0.1,
            "typescript": 0.05,
            "javascript": 0.0,
            "rust": -0.05,
            "c++": -0.1
        }.get(language, 0)
        
        return min(base_score + comment_bonus + language_bonus, 1.0)

    def _estimate_performance_retention(self, patterns: List[Dict[str, Any]]) -> float:
        """Estimate how much assembly performance is retained"""
        if not patterns:
            return 0.8
        
        # Average efficiency of detected patterns
        efficiencies = []
        for pattern in patterns:
            # Mock efficiency based on pattern type
            efficiency_map = {
                "mov": 0.95,
                "jmp": 0.85, 
                "call": 0.80,
                "cmp": 0.90,
                "push": 0.85,
                "pop": 0.85,
                "loop": 0.90
            }
            efficiencies.append(efficiency_map.get(pattern["type"], 0.75))
        
        return sum(efficiencies) / len(efficiencies)

