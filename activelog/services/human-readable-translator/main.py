    async def _answer_what_systems_use_it(self, code_snippet: str, user_level: str, language: str) -> str:
        """Answer 'What systems use this kind of code?' - explain real-world applications"""
        patterns = self._detect_assembly_patterns(code_snippet) if language == "assembly" else self._detect_highlevel_patterns(code_snippet, language)
        
        # Map patterns to system types
        system_types = set()
